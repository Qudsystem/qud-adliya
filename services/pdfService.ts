
/**
 * ADLIYA SUPREME PDF SERVICE v2.0
 * Using html2pdf for full RTL and Arabic support.
 */

export const downloadAsPDF = async (title: string, content: string, language: 'ar' | 'en') => {
  // We use html2pdf which handles the complex Arabic glyph shaping and RTL layout perfectly
  // by rendering a hidden HTML element to a canvas and then to PDF.
  const html2pdf = (await import('https://esm.sh/html2pdf.js@0.10.1')).default;

  const isRtl = language === 'ar';
  
  // Create a professional looking container for the PDF content
  const element = document.createElement('div');
  element.style.padding = '40px';
  element.style.fontFamily = isRtl ? "'Amiri', serif" : "'Inter', sans-serif";
  element.style.direction = isRtl ? 'rtl' : 'ltr';
  element.style.color = '#1a1a1a';
  element.style.width = '700px'; // Standard A4-ish width for rendering
  element.style.backgroundColor = '#ffffff';

  const refId = Math.random().toString(36).substring(7).toUpperCase();
  const dateStr = new Date().toLocaleString(language === 'ar' ? 'ar-EG' : 'en-US');

  element.innerHTML = `
    <div style="border-bottom: 4px solid #b45309; padding-bottom: 20px; margin-bottom: 30px; display: flex; justify-content: space-between; align-items: center;">
      <div style="text-align: ${isRtl ? 'right' : 'left'}">
        <h1 style="margin: 0; color: #064e3b; font-size: 28px; font-weight: 900; letter-spacing: -1px;">ADLIYA SUPREME</h1>
        <p style="margin: 5px 0 0 0; color: #666; font-size: 12px; font-weight: bold; text-transform: uppercase;">${language === 'ar' ? 'تقرير الاستخبارات القانونية الرسمي' : 'Official Legal Intelligence Report'}</p>
      </div>
      <div style="text-align: ${isRtl ? 'left' : 'right'}; font-size: 10px; color: #999;">
        <div>Ref: ${refId}</div>
        <div>${dateStr}</div>
      </div>
    </div>

    <div style="margin-bottom: 40px;">
      <h2 style="font-size: 18px; color: #064e3b; border-bottom: 1px solid #eee; padding-bottom: 10px; margin-bottom: 20px;">${title}</h2>
      <div style="line-height: 1.8; font-size: 14px; text-align: justify; white-space: pre-wrap;">
        ${content}
      </div>
    </div>

    <div style="margin-top: 60px; padding-top: 20px; border-top: 1px solid #eee; text-align: center; font-size: 10px; color: #aaa;">
      <p style="margin-bottom: 5px;">${language === 'ar' ? 'هذا المستند تم إنشاؤه بواسطة منصة عدلية. هو مرجع استرشادي معتمد رقمياً.' : 'Generated by Adliya. Digitally verified guidance reference.'}</p>
      <p style="font-weight: bold; letter-spacing: 2px;">ADLIYA SUPREME ENGINE V3.5 • SECURE EXPORT</p>
    </div>
    
    <!-- Watermark -->
    <div style="position: absolute; top: 50%; left: 50%; transform: translate(-50%, -50%) rotate(-45deg); font-size: 100px; color: rgba(0,0,0,0.03); font-weight: 900; pointer-events: none; z-index: -1;">
      VERIFIED
    </div>
  `;

  const opt = {
    margin: 10,
    filename: `Adliya_Supreme_${refId}.pdf`,
    image: { type: 'jpeg', quality: 0.98 },
    html2canvas: { scale: 2, useCORS: true, letterRendering: true },
    jsPDF: { unit: 'mm', format: 'a4', orientation: 'portrait' }
  };

  // Run the conversion
  await html2pdf().from(element).set(opt).save();
};
